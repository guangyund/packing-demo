"""
三维装箱系统 - 全局约束配置

所有装箱约束条件统一在此文件管理，修改后重启服务即可生效。
"""

# ── 重量约束 ──────────────────────────────────────────────────────────────────

# 每箱最大承重（kg）。系统级硬约束，优先级高于箱型自身限重。
# 例：箱型限重 50kg，此值设为 22，则实际限重取 22kg。
MAX_BIN_WEIGHT = 22

# ── 推荐包材尺寸约束 ──────────────────────────────────────────────────────────

# 推荐新包材时，箱型三边的最大尺寸限制（cm）。
# 规则：最长边不超过 MAX_BIN_LONG_SIDE，另外两边不超过 MAX_BIN_SHORT_SIDE。
MAX_BIN_LONG_SIDE  = 91.0   # 最长边上限（cm）
MAX_BIN_SHORT_SIDE = 63.5   # 另外两边上限（cm）

# 推荐包材时在实测包围盒基础上加的缓冲余量（cm）。
BIN_SIZE_BUFFER = 0.5

# 推荐包材尺寸向上取整的精度（cm）。与 BIN_SIZE_BUFFER 配合使用：
# 精度设为 0.5 时，ceil((43 + 0.5) / 0.5) × 0.5 = 43.5，buffer 才能生效。
# 若保留精度 1cm，ceil((43 + 0.5) / 1) × 1 = 44，与 buffer=1.0 结果相同。
BIN_SIZE_ROUND_TO = 0.5

# ── AI 推荐触发阈值 ───────────────────────────────────────────────────────────

# 当装箱平均利用率低于此值时，触发推荐新包材流程。
# 例：0.4 表示利用率 < 40% 时认为现有箱型不合适，开始推荐。
MIN_UTILIZATION_THRESHOLD = 0.65

# ── OR-Tools 求解器参数 ───────────────────────────────────────────────────────

# OR-Tools 每箱最长计算时间（秒）。值越大结果越优，但响应越慢。
# 货物种类少时 2~3 秒足够；货物复杂时可调到 5~10 秒。
ORTOOLS_TIME_LIMIT = 1.5

# OR-Tools 并行搜索线程数。建议设为服务器 CPU 核心数。
# 腾讯云 2 核服务器建议设为 2，4 核设为 4，本地开发可设为 8。
ORTOOLS_NUM_WORKERS = 8

# ── 软包材参数 ────────────────────────────────────────────────────────────────

# 方案三公式：pkg_L = stack_L + stack_H × FACTOR + SEAL_BASE
# pkg_W = stack_W + SIDE_MARGIN × 2，pkg_H = stack_H
SOFT_PKG_HEIGHT_FACTOR = 0.5   # 底部弯折折算比例
SOFT_PKG_SEAL_BASE     = 0.0   # 封口区固定留量（cm）
SOFT_PKG_SIDE_MARGIN   = 0.2   # 两侧余量（cm），pkg_W 两侧各加此值
SOFT_PKG_MAX_WEIGHT    = 10.0  # 软包材重量上限（kg）

# ── 物理约束 ──────────────────────────────────────────────────────────────────

# 是否启用重力沉降（消除货物浮空）。
# True：装箱结果经过重力模拟，所有货物落到最低合法位置，3D 展示无浮空。
# False：关闭沉降，坐标完全由算法输出，可能出现货物悬空。
ENABLE_GRAVITY_SETTLING = True

# 是否启用底面支撑率检查（防止货物"架桥"悬空）。
# True：货物底面必须有足够比例被支撑，否则自动下沉至更低的有效支撑位置。
# False：关闭检查，仅按最高可落点放置（可能出现悬空架桥）。
ENABLE_SUPPORT_CHECK = True

# 货物底面最小支撑面积比（0~1）。
# 货物底面面积中，至少此比例须由下方货物顶面或地面实际覆盖，才视为"有效支撑"。
# 推荐值：0.75（75%）。值越高约束越严，可能导致更多货物落到更低位置。
# 设为 0 等同于禁用（任意微小重叠即可），设为 1.0 要求底面完全贴合（过于严苛）。
MIN_ITEM_SUPPORT_RATIO = 0.75
